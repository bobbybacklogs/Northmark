import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { normalizeMarkdown, parseDocs } from '../src/docs.js';
import { NorthmarkError } from '../src/errors.js';
import { generateDocs } from '../src/generate.js';
import type { LlmClient, ModelConfig } from '../src/types.js';
import { makeTempDir, removeTemp, writeTree } from './helpers.js';

const temps: string[] = [];
const model: ModelConfig = {
  baseUrl: 'https://example.test/v1',
  apiKey: 'test-key',
  model: 'modelhitch/auto',
  timeoutMs: 5_000,
};

afterEach(async () => {
  await Promise.all(temps.splice(0).map((dir) => removeTemp(dir)));
});

async function project(): Promise<string> {
  const dir = await makeTempDir();
  temps.push(dir);
  await writeTree(dir, {
    'package.json': '{ "name": "sample", "dependencies": { "react": "18.3.1" } }\n',
    'src/App.tsx': 'export function App(){ return "hello"; }\n',
    'src/app.css': 'body { color: #7c3aed; font-family: "Source Serif 4", serif; }\n',
  });
  return dir;
}

function fakeLlm(failOn?: string): { client: LlmClient; calls: string[] } {
  const calls: string[] = [];
  const client: LlmClient = {
    async complete({ user }) {
      const name = user.match(/Document to write: (\S+)/)?.[1] ?? 'doc';
      calls.push(name);
      if (failOn && name === failOn) throw new NorthmarkError('The model endpoint returned 503.');
      return `# ${name}\n\nGrounded in the source.\n`;
    },
  };
  return { client, calls };
}

describe('generateDocs', () => {
  it('does not call the model or write files on a dry run', async () => {
    const cwd = await project();
    const { client, calls } = fakeLlm();
    const result = await generateDocs({
      cwd,
      docs: ['readme', 'product-brief', 'design', 'architecture'],
      outDir: 'docs',
      force: false,
      dryRun: true,
      maxBytes: 50_000,
      model,
      llm: client,
    });
    expect(calls).toEqual([]);
    expect(result.dryRun).toBe(true);
    expect(result.planned.map((doc) => doc.relativePath)).toEqual([
      'docs/README.md',
      'docs/product_brief.md',
      'docs/design_direction.md',
      'docs/architecture.md',
    ]);
    await expect(access(path.join(cwd, 'docs'))).rejects.toThrow();
  });

  it('writes the four alignment docs from the model', async () => {
    const cwd = await project();
    const { client, calls } = fakeLlm();
    const result = await generateDocs({
      cwd,
      docs: ['readme', 'product-brief', 'design', 'architecture'],
      outDir: 'docs',
      force: false,
      dryRun: false,
      maxBytes: 50_000,
      model,
      llm: client,
    });
    expect(calls).toEqual([
      'README.md',
      'product_brief.md',
      'design_direction.md',
      'architecture.md',
    ]);
    expect(result.written).toHaveLength(4);
    for (const doc of result.written) {
      const body = await readFile(doc.absolutePath, 'utf8');
      expect(body).toContain('Generated by Northmark');
      expect(body).toContain(`# ${doc.filename}`);
      expect(body.endsWith('\n')).toBe(true);
    }
  });

  it('refuses to overwrite unless forced or confirmed', async () => {
    const cwd = await project();
    await mkdir(path.join(cwd, 'docs'));
    const readme = path.join(cwd, 'docs/README.md');
    await writeFile(readme, 'original readme\n');
    const { client, calls } = fakeLlm();

    await expect(generateDocs({
      cwd,
      docs: ['readme'],
      outDir: 'docs',
      force: false,
      dryRun: false,
      maxBytes: 50_000,
      model,
      llm: client,
    })).rejects.toThrow(/--force/);
    expect(calls).toEqual([]);
    expect(await readFile(readme, 'utf8')).toBe('original readme\n');

    const confirmed = await generateDocs({
      cwd,
      docs: ['readme'],
      outDir: 'docs',
      force: false,
      dryRun: false,
      maxBytes: 50_000,
      model,
      llm: client,
      confirmOverwrite: async () => false,
    });
    expect(confirmed.cancelled).toBe(true);
    expect(await readFile(readme, 'utf8')).toBe('original readme\n');

    await generateDocs({
      cwd,
      docs: ['readme'],
      outDir: 'docs',
      force: true,
      dryRun: false,
      maxBytes: 50_000,
      model,
      llm: client,
    });
    const replaced = await readFile(readme, 'utf8');
    expect(replaced).toContain('# README.md');
    expect(replaced).not.toContain('original readme');
  });

  it('writes nothing when a later model call fails', async () => {
    const cwd = await project();
    await mkdir(path.join(cwd, 'docs'));
    await writeFile(path.join(cwd, 'docs/README.md'), 'original readme\n');
    const { client } = fakeLlm('product_brief.md');
    await expect(generateDocs({
      cwd,
      docs: ['readme', 'product-brief'],
      outDir: 'docs',
      force: true,
      dryRun: false,
      maxBytes: 50_000,
      model,
      llm: client,
    })).rejects.toThrow(/Nothing was written/);
    expect(await readFile(path.join(cwd, 'docs/README.md'), 'utf8')).toBe('original readme\n');
    await expect(access(path.join(cwd, 'docs/product_brief.md'))).rejects.toThrow();
  });

  it('refuses an output directory outside the project', async () => {
    const cwd = await project();
    const { client, calls } = fakeLlm();
    await expect(generateDocs({
      cwd,
      docs: ['readme'],
      outDir: '../outside-docs',
      force: true,
      dryRun: true,
      maxBytes: 50_000,
      model,
      llm: client,
    })).rejects.toThrow(/outside the project/);
    expect(calls).toEqual([]);
  });

  it('marks existing files on a dry run without writing', async () => {
    const cwd = await project();
    await mkdir(path.join(cwd, 'docs'));
    await writeFile(path.join(cwd, 'docs/README.md'), 'keep me\n');
    const { client } = fakeLlm();
    const result = await generateDocs({
      cwd,
      docs: ['readme', 'architecture'],
      outDir: 'docs',
      force: false,
      dryRun: true,
      maxBytes: 50_000,
      model,
      llm: client,
    });
    const readme = result.planned.find((doc) => doc.filename === 'README.md');
    const architecture = result.planned.find((doc) => doc.filename === 'architecture.md');
    expect(readme?.existed).toBe(true);
    expect(architecture?.existed).toBe(false);
    expect(await readFile(path.join(cwd, 'docs/README.md'), 'utf8')).toBe('keep me\n');
  });
});

describe('doc helpers', () => {
  it('parses doc aliases and rejects unknown names', () => {
    expect(parseDocs(undefined)).toEqual(['readme', 'product-brief', 'design', 'architecture']);
    expect(parseDocs('brief, design_direction')).toEqual(['product-brief', 'design']);
    expect(() => parseDocs('nope')).toThrow(/Unknown doc/);
  });

  it('strips a wrapping markdown fence', () => {
    const text = normalizeMarkdown('```markdown\n# Hello\n\nBody.\n```');
    expect(text).toContain('# Hello');
    expect(text).not.toMatch(/^```/);
    expect(text).toContain('Generated by Northmark');
    expect(text.endsWith('\n')).toBe(true);
  });
});
