const GENERATED_NOTE = '<!-- Generated by Northmark. Grounded in the source at generation time. Edit freely. -->';

export function parseDocs(input: string | undefined): DocId[] {
  if (input == null || input.trim() === '' || input.trim().toLowerCase() === 'all') {
    return DOC_SPECS.map((spec) => spec.id);
  }
  const parts = input.split(/[,\s]+/).map((part) => part.trim().toLowerCase()).filter(Boolean);
  const ids: DocId[] = [];
  for (const part of parts) {
    const spec = DOC_SPECS.find((item) => item.id === part || item.aliases.includes(part));
    if (!spec) {
      throw new NorthmarkError(`Unknown doc "${part}". Choose from: ${DOC_SPECS.map((item) => item.id).join(', ')}.`);
    }
    if (!ids.includes(spec.id)) ids.push(spec.id);
  }
  if (ids.length === 0) {
    throw new NorthmarkError(`Choose at least one doc. Options: ${DOC_SPECS.map((item) => item.id).join(', ')}.`);
  }
  return ids;
}

export function specsFor(ids: DocId[]): DocSpec[] {
  return ids.map((id) => {
    const spec = DOC_SPECS.find((item) => item.id === id);
    if (!spec) throw new NorthmarkError(`Unknown doc "${id}".`);
    return spec;
  });
}

export function promptFor(spec: DocSpec, context: string): { system: string; user: string } {
  return {
    system: SYSTEM_PROMPT,
    user: `Document to write: ${spec.filename}\n\n${spec.instruction}\n\n---\n\n${context}`,
  };
}

export function normalizeMarkdown(raw: string): string {
  let text = raw.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').trim();
  const wrapped = text.match(/^```(?:markdown|md)?\s*\n([\s\S]*?)\n```$/i);
  if (wrapped?.[1]) text = wrapped[1].trim();
  if (!text.includes('Generated by Northmark')) {
    text = `${GENERATED_NOTE}\n\n${text}`;
  }
  if (!text.endsWith('\n')) text += '\n';
  return text;
}

export function resolveOutputDir(cwd: string, outDir: string): string {
  const root = path.resolve(cwd);
  const absolute = path.resolve(root, outDir);
  if (!isInsideRoot(root, absolute)) {
    throw new NorthmarkError(`Refusing to write outside the project: ${outDir}`);
  }
  return absolute;
}

export function planDocs(cwd: string, outDir: string, ids: DocId[], exists: (absolute: string) => boolean): PlannedDoc[] {
  const root = path.resolve(cwd);
  const absoluteOut = resolveOutputDir(root, outDir);
  return specsFor(ids).map((spec) => {
    const absolutePath = path.join(absoluteOut, spec.filename);
    if (!isInsideRoot(root, absolutePath)) {
      throw new NorthmarkError(`Refusing to write outside the project: ${spec.filename}`);
    }
    return {
      id: spec.id,
      filename: spec.filename,
      absolutePath,
      relativePath: toPosix(path.relative(root, absolutePath)),
      existed: exists(absolutePath),
    };
  });
}

export async function writePlannedDoc(doc: PlannedDoc, markdown: string): Promise<void> {
  try {
    await mkdir(path.dirname(doc.absolutePath), { recursive: true });
    await writeFile(doc.absolutePath, normalizeMarkdown(markdown), 'utf8');
  } catch (error) {
    const reason = error instanceof Error ? error.message : 'unknown error';
    throw new NorthmarkError(`Couldn't write ${doc.relativePath}: ${reason}`);
  }
}
